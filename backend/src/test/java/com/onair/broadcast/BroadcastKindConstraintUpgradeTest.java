package com.onair.broadcast;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/** v0.1.0이 만든 DB(kind에 RECORDING만 허용하는 검사 제약)에서 라이브방송을 저장할 수 있게 되는지 본다. */
class BroadcastKindConstraintUpgradeTest {

    JdbcTemplate jdbc;

    @BeforeEach
    void v010_스키마를_만든다() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("""
                create table broadcast (
                    id bigint generated by default as identity,
                    kind varchar(20) not null check (kind in ('RECORDING')),
                    title varchar(100) not null,
                    primary key (id))""");
        jdbc.update("insert into broadcast (kind, title) values ('RECORDING', '1단계 방송')");
    }

    @Test
    void 오래된_제약을_바꾸면_LIVE를_저장할_수_있고_기존_데이터는_남는다() {
        new BroadcastKindConstraintUpgrade(jdbc).upgrade();

        jdbc.update("insert into broadcast (kind, title) values ('LIVE', '라이브')");
        assertThat(jdbc.queryForList("select kind from broadcast order by id", String.class))
                .containsExactly("RECORDING", "LIVE");
    }

    @Test
    void 지금의_종류를_모두_허용하는_제약은_남긴다() {
        JdbcTemplate fresh = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", ""));
        fresh.execute("""
                create table broadcast (
                    id bigint generated by default as identity,
                    kind varchar(20) not null check (kind in ('LIVE', 'RECORDING')),
                    title varchar(100) not null,
                    primary key (id))""");

        new BroadcastKindConstraintUpgrade(fresh).upgrade();

        assertThatThrownBy(() -> fresh.update("insert into broadcast (kind, title) values ('OTHER', 'x')"))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void 여러_번_실행해도_결과가_같다() {
        BroadcastKindConstraintUpgrade upgrade = new BroadcastKindConstraintUpgrade(jdbc);
        upgrade.upgrade();
        upgrade.upgrade();

        jdbc.update("insert into broadcast (kind, title) values ('LIVE', '라이브')");
        assertThat(jdbc.queryForObject("select count(*) from broadcast", Integer.class)).isEqualTo(2);
    }
}
